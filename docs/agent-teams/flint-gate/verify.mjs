import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../../../',import.meta.url));process.chdir(root);
const base='docs/agent-teams/flint-gate';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const hash=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const {team,state}=read(`${base}/team-request.json`);
assert.equal(team.id,'flint-gate');assert.equal(team.roles.length,10);
assert.equal(new Set(team.roles.map(r=>r.id)).size,10);
const skillIds=[...new Set(team.roles.flatMap(r=>r.skills))];assert.equal(skillIds.length,10);
for(const skill of skillIds){
 const s=fs.readFileSync(`.agents/skills/${skill}/SKILL.md`,'utf8');
 assert.ok(s.startsWith(`---\nname: ${skill}\n`));
 const front=s.split('\n---\n')[0];assert.ok(front.includes('description: '));
 assert.ok(JSON.parse(front.match(/^description: (.*)$/m)[1]).length<=1024);
 assert.ok(!s.includes('TODO')&&!s.includes('TBD'));
}
if(fs.existsSync(state))assert.deepEqual(read(state).team,team,'Runtime ledger differs from canonical manifest');
const graph=read('compass-out/verification/verification.json');
for(const file of graph.files)assert.equal(`sha256:${hash(file.path)}`,file.contentDigest,`Graph source changed: ${file.path}`);
const owners=p=>team.roles.filter(r=>r.owns.some(g=>path.matchesGlob(p,g))).map(r=>r.id);
const ownership=graph.files.map(f=>({path:f.path,owners:owners(f.path)}));
for(const f of ownership)assert.equal(f.owners.length,1,`Expected one owner: ${JSON.stringify(f)}`);
const tracked=execFileSync('git',['ls-files','-z'],{encoding:'utf8'}).split('\0').filter(Boolean);
const overlaps=tracked.map(p=>({path:p,owners:owners(p)})).filter(f=>f.owners.length>1);
assert.deepEqual(overlaps,[],'Overlapping tracked write ownership');
const selectedModels=[];
for(const role of team.roles){
 const selected=read(`${base}/evidence/model-${role.id}.json`).selected;
 assert.ok(selected?.id);assert.equal(role.native.codex.model,selected.id);
 assert.equal(role.modelPolicy.tier,selected.tier);
 selectedModels.push({role:role.id,codex:selected.id,tier:selected.tier});
}
const targets=['codex','claude','copilot','kimi','minimax','opencode','deepseek','uar','bossfang'];
let exportFiles=0;
for(const target of targets){
 const dir=`${base}/exports/${target}`;
 const receipt=read(`${dir}/team-export.json`);
 for(const item of receipt.files){assert.equal(hash(`${dir}/${item.file}`),item.sha256,`Export changed: ${target}/${item.file}`);exportFiles++;}
 assert.equal(read(`${dir}/export-receipt.json`).target,target);
}
const install=read(`${base}/evidence/project-installation.json`);
for(const file of install.files){assert.equal(hash(file.destination),hash(file.source),`Installed definition differs: ${file.destination}`);assert.equal(hash(file.destination),file.sha256);}
for(const link of install.links){assert.equal(fs.readlinkSync(link.destination),link.target);assert.ok(fs.existsSync(link.destination));}
// Validate the exact formats generated by the adapter, not a substitute native schema.
function frontmatter(p){const text=fs.readFileSync(p,'utf8');const match=text.match(/^---\n([\s\S]*?)\n---\n/);assert.ok(match,p);return JSON.parse(match[1]);}
for(const role of team.roles){
 const toml=fs.readFileSync(`.codex/agents/${role.id}.toml`,'utf8');
 const keys=Object.fromEntries(toml.trim().split('\n').map(line=>{const m=line.match(/^("[^"]+") = (.*)$/);assert.ok(m);return [JSON.parse(m[1]),JSON.parse(m[2])];}));
 assert.equal(keys.name,role.id);assert.equal(keys.model,role.native.codex.model);assert.ok(keys.developer_instructions.includes(role.owns[0]));
 for(const [dir,ext] of [['.claude/agents','.md'],['.github/agents','.agent.md'],['.kimi-code/agents','.md'],['.opencode/agents','.md'],['.agent-team/minimax/agents','/agent.md']]){
  const meta=frontmatter(`${dir}/${role.id}${ext}`);assert.ok(meta.description);if(meta.name)assert.equal(meta.name,role.id);
  if(dir==='.opencode/agents'){assert.equal(meta.mode,'subagent');assert.equal(meta.model,role.native.opencode.model);}
  if(dir==='.kimi-code/agents')assert.ok(!Object.hasOwn(meta,'model'),'Kimi role model field is unsupported');
 }
 const patch=read(`${base}/exports/deepseek/.dsh/profiles/flint-gate-${role.id}/cordis.patch.yml`);assert.ok(Array.isArray(patch));assert.ok(patch[0].insert[0].config.prefix.includes(role.id));
 const uar=read(`${base}/exports/uar/uar/agents/${role.id}.json`);assert.ok(uar);
}
const nativeList=fs.readFileSync(`${base}/evidence/opencode-agent-list.txt`,'utf8');
for(const role of team.roles)assert.ok(nativeList.includes(`${role.id} (subagent)`),`OpenCode did not discover ${role.id}`);
// Verify local Markdown links in the authored entrypoints and skills.
const docs=[`${base}/README.md`,`${base}/WORKFLOW.md`,`${base}/RESEARCH.md`,'.compass/README.md',...skillIds.map(s=>`.agents/skills/${s}/SKILL.md`)];
for(const p of docs){for(const m of fs.readFileSync(p,'utf8').matchAll(/\[[^\]]*\]\(([^)]+)\)/g)){
 const link=m[1];if(/^(https?:|#)/.test(link))continue;
 const resolved=path.resolve(path.dirname(p),link.split('#')[0]);
 if(resolved===path.join(root,base,'evidence/validation.json'))continue;
 assert.ok(fs.existsSync(resolved),`Broken link in ${p}: ${link}`);
}}
let setupAudit;
if(process.argv.includes('--setup-audit')){
 const baseline=read('.compass/setup-baseline.json');
 const changed=Object.entries(baseline.trackedHashes).filter(([p,h])=>hash(p)!==h).map(([p])=>p);
 assert.deepEqual(changed,['.gitignore'],'Pre-existing tracked file changed during setup');
 setupAudit={baselineAt:baseline.at,sourceHead:baseline.head,trackedFilesChecked:Object.keys(baseline.trackedHashes).length,changedTrackedFiles:changed,preExistingModifiedSourceFiles:baseline.status.trim().split('\n').filter(Boolean).length,preserved:true};
}
const receipt={checkedAt:new Date().toISOString(),sourceHead:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),roles:10,skills:10,indexedFilesWithExactlyOneOwner:ownership.length,ownership,overlappingTrackedPaths:[],selectedModels,exportTargets:targets,exportFilesVerified:exportFiles,installedFilesVerified:install.files.length,skillLinksVerified:install.links.length,nativeVerification:{opencode:'10 subagents discovered by agent list --pure; no model run',codex:'Generated quoted-key TOML fields and installed bytes checked; no agent run',claude:'Frontmatter and installed bytes checked; no agent run',kimi:'Frontmatter and installed bytes checked; no agent run',copilot:'Frontmatter and installed bytes checked; no agent run',minimax:'Frontmatter and isolated-profile bytes checked; runtime acceptance unverified',deepseek:'JSON-compatible Cordis patch parsed; external wrapper fails pnpm version check',uar:'Staged artifact JSON parsed; no registration',bossfang:'Export hashes verified; no registration/activation'},graphSha256:graph.graphSha256,setupAudit,limits:['Ownership globs coordinate writes; they do not enforce native filesystem permissions.','Format checks are not full native schema certification or successful inference.','OpenCode discovery receipt is the recorded setup check; rerun the CLI after changing native definitions.','Unassigned future paths require ownership reconciliation before edits.']};
fs.writeFileSync(`${base}/evidence/validation.json`,JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({roles:10,skills:10,indexedFilesOwned:ownership.length,exportFilesVerified:exportFiles,installedFilesVerified:install.files.length,skillLinksVerified:install.links.length,setupAudit},null,2));
